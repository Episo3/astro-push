def shower_intensity(shower: Shower, day: date, ) -> float:
    """距峰值越近强度越高（0-1）。"""
    peak = shower.peak_date(day.year)
    delta = abs((day - peak).days)
    if delta == 0:
        return 1.0
    if delta <= 1:
        return 0.75
    if delta <= 3:
        return 0.45
    if delta <= 6:
        return 0.2
    return 0.05


def active_showers(day: date) -> list[tuple[Shower, float]]:
    out = []
    for s in METEOR_SHOWERS:
        if s.active_on(day):
            out.append((s, shower_intensity(s, day)))
    return sorted(out, key=lambda x: -x[1])


def upcoming_showers(day: date, horizon_days: int = 60) -> list[tuple[Shower, int]]:
    """未来 N 天内将达峰（或正处于活动期）的流星雨。"""
    out = []
    for s in METEOR_SHOWERS:
        peak = s.peak_date(day.year)
        if peak < day - timedelta(days=15):
            peak = s.peak_date(day.year + 1)
        delta = (peak - day).days
        if -15 <= delta <= horizon_days:
            out.append((s, delta))
    return sorted(out, key=lambda x: x[1])


