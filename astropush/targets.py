# --------------------------------------------------------------------------- #
# 流星雨（IMO 主要流星雨，日期为峰值附近）
# --------------------------------------------------------------------------- #
@dataclass
class Shower:
    key: str
    name: str
    cname: str
    peak: tuple[int, int]      # 峰值（月, 日）
    zhr: int
    ra: float                  # 辐射点赤经（度）
    dec: float                 # 辐射点赤纬（度）
    speed: float               # 速度 km/s
    start: tuple[int, int]
    end: tuple[int, int]
    note: str = ""

    def peak_date(self, year: int) -> date:
        return date(year, *self.peak)

    def active_on(self, d: date) -> bool:
        """是否处于活动期（处理跨年）。"""
        y = d.year
        try:
            s, e = date(y, *self.start), date(y, *self.end)
        except ValueError:
            return False
        if s <= e:
            return s <= d <= e
        return d >= s or d <= e


